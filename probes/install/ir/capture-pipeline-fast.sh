#!/usr/bin/env bash
# Regenerate the fused mask passes' emitted-IR fixture and its census.
#
# Run from the repository root:
#
#   nix develop -c bash probes/install/ir/capture-pipeline-fast.sh
#
# Input
#   kernel/json/pipeline_fast.c     the two fused mask passes (bench candidate)
#
# Output
#   pipeline_fast.candidate.ll      the two `define` blocks, normalised
#   pipeline_fast.strip.tsv         the tokens the normalisation removed, by class
#   pipeline_fast.rewrites.tsv      what it rewrote rather than removed, with why
#   pipeline_fast.inventory         blocks, opcodes and call targets of each pass
#
# --- The compiler line ---
#
# The flags are the measured build's (`-O3 -march=x86-64-v3 -mpclmul
# -std=gnu11 -falign-loops=64 -falign-functions=64`, plus
# `-fno-discard-value-names` for the source's value names and labels), with one
# addition: `-fno-inline-functions`.  At the measured line both passes are
# inlined into their wrappers and their helpers into the passes, so neither pass
# has a `define` block of its own.  The addition keeps the pass and its helpers
# out of line; the instruction stream inside the pass is the source's, and the
# difference from the object is the inlining boundary, recorded in
# pipeline_fast.rewrites.tsv.  `pf_mask_core`'s emission drops the unused
# `xp`/`nxp`/`xc` parameters (three parameters, not six); that is the source's
# `(void)xp; (void)nxp; (void)xc;` seen by the optimiser, and it is recorded
# too.
#
# --- The struct extent ---
#
# The carry is `%struct.s1_carry`, three `i64` fields, 24 bytes.  The fixture
# carries no `%struct` definition: the parser takes a named struct's extent from
# the layout its caller declares, so the IR module parses with
# `[("s1_carry", 24)]`.  The extent is the target datalayout's, not recomputed
# from the fields.
#
# --- The normalisation ---
#
# The emission carries syntax the parser refuses by name; each removal is one of
# the classes in pipeline_fast.strip.tsv (attributes, function-header surface,
# constraining flags, alignment, calling conventions, metadata).  The parser's
# own tokenizer drops comment and blank lines, so they are dropped here too.
#
# Exit status: 0 when the four artefacts are written; 3 when the emission has no
# `define` block for a pass or the naming flag changes an instruction.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../../.." && pwd)

src=kernel/json/pipeline_fast.c
fixture=$here/pipeline_fast.candidate.ll
strip=$here/pipeline_fast.strip.tsv
rewrites=$here/pipeline_fast.rewrites.tsv
inventory=$here/pipeline_fast.inventory

fail() { printf 'SETUP: %s\n' "$*" >&2; exit 3; }

[ -f "$repo/$src" ] || fail "absent: $repo/$src"
command -v clang >/dev/null 2>&1 || fail "clang is not on PATH"

work=$(mktemp -d) || fail "cannot create a work directory"
trap 'rm -rf "$work"' EXIT

flags=(-S -emit-llvm -O3 -march=x86-64-v3 -mpclmul -std=gnu11
       -falign-loops=64 -falign-functions=64 -fno-inline-functions)

compile() { ( cd "$repo" && clang "$@" ); }

compile "${flags[@]}" "$src" -o "$work/plain.ll"
compile "${flags[@]}" -fno-discard-value-names "$src" -o "$work/named.ll"

# The naming flag's claim, checked: the same source, the same instructions.
neutralise() {
  sed -E -e 's/%[A-Za-z0-9._$-]+/%N/g' \
         -e '/^[A-Za-z0-9_.]+:([[:space:]]*;.*)?$/d' "$1"
}
neutralise "$work/plain.ll" > "$work/plain.norm.ll"
neutralise "$work/named.ll" > "$work/named.norm.ll"
cmp -s "$work/plain.norm.ll" "$work/named.norm.ll" ||
  fail "-fno-discard-value-names changed the emission beyond register names"

extract_block() {
  local sym=$1
  awk -v s="@$sym(" '
    index($0, "define ") == 1 && index($0, s) > 0 { p = 1 }
    p { print }
    p && $0 == "}" { exit }
  ' "$work/named.ll"
}

normalise() {
  sed -E \
    -e 's/ noundef//g' -e 's/ nonnull//g' -e 's/ readonly//g' -e 's/ writeonly//g' \
    -e 's/ captures\([^)]*\)//g' -e 's/ dereferenceable\([^)]*\)//g' \
    -e 's/ initializes\(\([^)]*\)\)//g' \
    -e 's/ local_unnamed_addr//g' -e 's/ unnamed_addr//g' -e 's/ #[0-9]+//g' \
    -e 's/, align [0-9]+//g' -e 's/ align [0-9]+//g' \
    -e 's/ range\(i64 [^)]*\)//g' \
    -e 's/ fastcc//g' -e 's/ zeroext//g' -e 's/ signext//g' -e 's/ inreg//g' \
    -e 's/ nuw//g' -e 's/ nsw//g' -e 's/ nneg//g' -e 's/ disjoint//g' \
    -e 's/ samesign//g' -e 's/ immarg//g' \
    -e 's/, !tbaa ![0-9]+//g' -e 's/, !llvm\.loop ![0-9]+//g'
}

{
  echo '; pipeline_fast.candidate.ll -- the two fused mask passes as emitted.'
  echo ';'
  echo '; Generated by probes/install/ir/capture-pipeline-fast.sh from'
  echo '; kernel/json/pipeline_fast.c at the measured compiler line'
  echo '; (-O3 -march=x86-64-v3 -mpclmul -std=gnu11 -falign-loops=64'
  echo '; -falign-functions=64 -fno-discard-value-names) plus -fno-inline-functions:'
  echo '; the passes and their helpers are out of line, where the measured object'
  echo '; inlines them. The body'"'"'s instructions are the source'"'"'s; the inlining'
  echo '; boundary is the fixture'"'"'s one derivation, recorded in pipeline_fast.rewrites.tsv.'
  echo ';'
  echo '; The struct allocas take their byte extent from the parser'"'"'s declared layout'
  echo '; ("s1_carry", 24); the fixture carries no `%struct` type definition because'
  echo '; the parser reads a named struct'"'"'s extent from that layout.'
  for sym in pf_mask_core pf_mask_list; do
    block=$(extract_block "$sym") || fail "no define block for @$sym"
    [ -n "$block" ] || fail "the define block of @$sym is empty"
    printf '%s\n\n' "$(printf '%s\n' "$block" | normalise)"
  done
} > "$fixture"

# --- the census -----------------------------------------------------------

{
  echo "# pipeline_fast.inventory -- the two passes' structure, from the fixture."
  echo "# function, blocks, alloca types, and the call targets in text order."
  for sym in pf_mask_core pf_mask_list; do
    awk -v sym="@$sym(" '
      index($0, "define ") == 1 && index($0, sym) > 0 { f = 1 }
      f { print }
      f && $0 == "}" { exit }
    ' "$fixture" > "$work/$sym.body"
    b=$(grep -cE '^[A-Za-z0-9_.]+:' "$work/$sym.body")
    echo "@$sym blocks=$b"
    grep -E 'alloca ' "$work/$sym.body" | sed -E 's/^.*alloca //' |
      awk '{ printf "  alloca %s\n", $1 }'
    grep -E 'call ' "$work/$sym.body" | grep -oE '@[A-Za-z0-9_.]+' |
      sort | uniq -c | awk '{ printf "  call %s %s\n", $1, $2 }'
  done
} > "$inventory"

# --- what the normalisation removed, and what it rewrote ------------------

cat > "$strip" <<'TSV'
class	token	reason
1	attributes	noundef, nonnull, readonly, writeonly, captures(...), dereferenceable(...), initializes(...): a promise about an argument or result, re-established by the theorem's hypotheses
2	function-header surface	local_unnamed_addr, unnamed_addr, #N: linkage and code placement, for which the model has no semantics
4	constraining flags	nuw, nsw, nneg, disjoint, samesign, inreg: each excludes inputs, so removing it widens; the widening is recorded
9	alignment	align N, both the header's and a load/store/alloca's: the parser's load and store have no alignment field
10	calling conventions	fastcc, zeroext, signext: the model's calls are untyped and carry no convention
5	metadata	!tbaa, !llvm.loop and the module's metadata nodes: the model has no aliasing relation or loop model
8	module configuration	target datalayout, target triple, source_filename, and the %struct type definition: not read by the parser; the struct extent is supplied by the layout
TSV

cat > "$rewrites" <<'TSV'
item	reason
-fno-inline-functions	At the measured line the passes are inlined into their wrappers and their helpers into the passes, so no pass has its own define block. The flag keeps the pass and its helpers out of line; the pass's instruction stream is the source's, and the proof's callee rows are the helper models.
pf_mask_core's three parameters	clang elides the unused xp/nxp/xc parameters of the list-free macro ((void)xp; (void)nxp; (void)xc). The fixture's ABI is the optimized function's, and JsonPipelineFastStage1's passRun takes no xp/nxp on the list-free arm.
%struct.s1_carry extent	The fixture carries no type definition; the IR module parses with the layout ("s1_carry", 24), the target's extent for three i64 fields.
TSV

printf 'wrote %s, %s, %s, %s\n' "$fixture" "$strip" "$rewrites" "$inventory"
