#!/usr/bin/env bash
# Arm B: the extracted unit and the measured header are the same code at the
# unit's boundary.
#
#   nix develop -c bash kernel/json/identity/ir-identity.sh              # s1
#   nix develop -c bash kernel/json/identity/ir-identity.sh --tree-only
#   nix develop -c bash kernel/json/identity/ir-identity.sh --unit entry # the entry unit
#
# Units (`--unit s1` is the default, so every existing invocation keeps its
# meaning and its exit codes):
#
#   s1     the mask unit.  Two translation units define the same probe symbol
#          over a 64-byte block and a three-word carry: `oracle.c` includes the
#          vendored measured header and calls the measured `s1f_masks`;
#          `kernel_probe.c` includes `s1_block.c` and calls the extracted one.
#          The probe is lifted out of each module with `llvm-extract` and
#          `llvm-diff` compares the two single-function modules.
#   entry  the entry unit.  `entry_oracle.c` includes the vendored headers and
#          calls the measured `s1f_k_pos8` and `s1f_k_b8`; `entry_probe.c`
#          includes `entry.c` and calls the same two names.  Both are lifted
#          **by name**, together with the table's global, and the arm asserts
#          each lifted module holds exactly those two functions and no other,
#          so a probe that dragged a third function in, or a lift that dropped
#          one of the two, is a setup fault rather than identity.
#   utf8   the UTF-8 unit.  The stage is not a measured function, so the two
#          sides are two **texts** rather than two include paths: the measured
#          side is generated by `source-identity.sh --unit utf8 --stage-tu`
#          from the same line ranges the token arm reads, pasted into the
#          measured declarations, and compiled against the vendored `s1fuse.h`
#          and `u8kl.h` at the measured `-D` set; the extracted side is
#          `kernel/json/utf8.c`.  Both define `leanllvm_json_utf8`, which is
#          lifted from each side by name, so no extra probe symbol exists and
#          no wrapper can hide a difference.
#   escape the escape unit.  `escape_oracle.c` includes the vendored measured
#          text and defines the unit's two ABI entry points over the measured
#          `xl_lanes`/`xl_emit` and `us_dec_x`; `escape_probe.c` includes
#          `kernel/json/escape.c`, whose own ABI functions are the same text.
#          Both sides are lifted by name — the two entry points and the
#          out-of-line `us_dec_x` — and the arm asserts each lifted module
#          defines exactly those three and no other.
#
#   pipeline the assembled caller, `kernel/json/pipeline.c`.  It is not
#          extracted text, so the arm's claim is the relation between the three
#          texts that must agree: the emission of the source, the object built
#          from that same source, and the pinned fixture
#          `probes/install/ir/json-pipeline.candidate.ll`.  Their call censuses
#          -- the multiset of the six unit ABIs the body calls -- must be
#          equal, which is what makes "the object the theorem is about is the
#          object the timing arm measures" a checked relation rather than a
#          sentence.  Its two controls change one call target in a copy of the
#          source, and remove one call from a copy of the fixture; both must be
#          reported.
#
# All three units: both sides are compiled with the measured compiler line
# (`build49.sh:17`); `s1` adds the P2 `-D` set (`build49.sh:21`), `entry` the
# measured one (`build49.sh:19-21`) with `S1F_UTF8` left at its default because
# the entry unit is not the UTF-8 unit, and `utf8` the measured one with
# `S1F_UTF8=7` and `S1F_KL_DOC=1`, which is the arm that selects the stage.
# Identity is an empty `llvm-diff`: both sides are compiled, inlined and
# optimised by the same compiler, so this compares emitted code and not source
# text.  The flags carry no `-g`, so there is no debug info to strip; the
# module's own file name (`ModuleID`, `source_filename`) is removed from both
# sides, leaving the comparison about code.
#
# "Identical IR" means the instruction text -- every opcode, operand, type,
# constant and branch edge.  Analysis metadata is excluded only where that text
# is identical *and* the metadata difference has a cause named in the output.
# The three units differ here, and the difference is stated rather than shared:
#
#   s1     the TBAA struct-path node's field count follows the enumerated
#          deletion of the carry type's `prevS`/`bs_prevb`/`bs_prevs`.
#   entry  no exclusion.  The two lifted modules are the same node graph --
#          their node *numbers* differ because each side was serialised from a
#          different source module -- so the metadata sections are compared as
#          a canonical graph: every node's text with its references replaced by
#          the referenced node's canonical text (a cycle is the `distinct` loop
#          node's self-reference), and the two multisets must be equal.  That
#          sees a changed node kind, string or integer, and is blind only to a
#          rewiring between nodes whose canonical texts are identical, which is
#          why the node count is printed beside it.
#   utf8   the same canonical-graph comparison, for the same reason: its two
#          sides are serialised from different source modules.
#
# The entry unit's table is computed by `xl_pos8_init`, so the only place a
# table byte exists in the lifted module is the global's own initialiser, and
# that definition is part of the comparison.  `llvm-diff` compares code and not
# global initialisers, so the arm compares `@xl_pos8`'s definition itself: the
# table's content is a definition, and the instrument needs it, so this is the
# comparison rather than an exclusion.
# `--mutate-table` demonstrates that this half bites, and the route (not this
# arm) is what compares the table's *content*.
#
# Controls, run every time, because an arm that cannot see a change is not
# evidence:
#   s1     --mutate-table  one byte of `s1f_lo_tab` changed in a copy of the kernel
#          --mutate-op     one operand in `s1f_escaped` changed in a copy
#   entry  --mutate-table  row 0x2C of the table's initialiser changed (entry 0 -> 1)
#          --mutate-slot   one slot index in `s1f_ke_b8`'s chain changed
#   utf8   --mutate-table  one byte of `kl_t1` changed, in a throwaway copy of
#                           the vendored pair that the measured side includes
#          --mutate-nuw    one `nuw` removed from the measured side's lifted IR
# Each must be reported by the instrument that can see it, and both verdicts are
# printed for each control.
#
# Modes: default `--identity --controls`; `--identity` alone compares only.
#   --tree-only  refuse any input path outside the repository (exit 3).
#
# Exit status: 0 when the identity and the requested controls hold, 1 when one
# fails, 3 on a setup fault (an absent input or tool, a control that could not
# be applied), so an absent tool is never read as a difference or as identity.
set -uo pipefail

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../../.." && pwd)
readme=$repo/kernel/json/README.md
cc=clang
cflags=(-O3 -march=x86-64-v3 -mpclmul -std=gnu11 -falign-loops=64 -falign-functions=64)

unit=s1
pipeline=0
run_identity=0
run_controls=0
tree_only=0
any_mode=0

usage() {
  awk 'NR > 1 && /^set -/ { exit } NR > 1 { print }' "$0" | sed 's/^# \{0,1\}//' 
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --unit) shift; unit=${1:-}; [ -n "$unit" ] || { printf 'ir-identity: --unit needs a value\n' >&2; exit 3; } ;;
    --unit=*) unit=${1#--unit=} ;;
    --identity) run_identity=1; any_mode=1 ;;
    --controls) run_controls=1; any_mode=1 ;;
    --tree-only) tree_only=1 ;;
    -h|--help) usage; exit 0 ;;
    *) printf 'ir-identity: unknown argument %s\n' "$1" >&2; exit 3 ;;
  esac
  shift
done
if [ "$any_mode" -eq 0 ]; then run_identity=1; run_controls=1; fi

# The unit's own data: its kernel file, the probe TU or generator that supplies
# the measured side, the symbol(s) the lift names, the `-D` set, and whether
# the lifted module's functions are the probe or the two kernels by name.
case "$unit" in
  s1)
    kernel=$repo/kernel/json/s1_block.c
    oracle=$here/oracle.c
    probe_src=$here/kernel_probe.c
    probe=stage1_block_probe
    defs=(-DPSTAGE=32 -DPMODE=2 -DS1F_XS=5 -DS2_XP=1 -DS2_DEC_GATE=2 -DS1F_XS_DYN=1)
    lift=(-func="$probe")
    lift_functions=""
    by_name=0
    generated=0
    ;;
  entry)
    kernel=$repo/kernel/json/entry.c
    oracle=$here/entry_oracle.c
    probe_src=$here/entry_probe.c
    probe=entry_stream_probe
    # `build49.sh:19-21`'s measured set, with the UTF-8 switch at its default
    # 0: this unit is not the UTF-8 unit, and nothing here reaches that stage.
    defs=(-DSTAGE_PROBE -DS1F_ENT_PROBE=1 -DS1F_DENS=1 -DS1F_TWOPHASE=1
          -DS1F_EXP2=11 -DS1F_DISPATCH=1 -DS1F_UTF8=0 -DS1F_KL_DOC=0 -DPSTAGE=32
          -DPMODE=2 -DS1F_XS=5 -DS2_XP=1 -DS2_DEC_GATE=2 -DS1F_XS_DYN=1)
    lift=(-func=s1f_k_pos8 -func=s1f_k_b8 -glob=xl_pos8)
    lift_functions="s1f_k_b8 s1f_k_pos8"
    by_name=1
    generated=0
    ;;
  utf8)
    kernel=$repo/kernel/json/utf8.c
    # The measured side has no probe TU of its own: it is generated from the
    # stage's line ranges by the token arm's helper, which is why that script
    # is this unit's second input.
    oracle=$here/source-identity.sh
    probe_src=""
    probe=leanllvm_json_utf8
    # `build49.sh:19-21`'s measured set with `S1F_UTF8=7` and `S1F_KL_DOC=1`,
    # the arm that selects the stage.
    defs=(-DSTAGE_PROBE -DS1F_ENT_PROBE=1 -DS1F_DENS=1 -DS1F_TWOPHASE=1
          -DS1F_EXP2=11 -DS1F_DISPATCH=1 -DS1F_UTF8=7 -DS1F_KL_DOC=1 -DPSTAGE=32
          -DPMODE=2 -DS1F_XS=5 -DS2_XP=1 -DS2_DEC_GATE=2 -DS1F_XS_DYN=1)
    lift=(-func="$probe")
    lift_functions="$probe"
    by_name=0
    generated=1
    ;;
  escape)
    kernel=$repo/kernel/json/escape.c
    oracle=$here/escape_oracle.c
    probe_src=$here/escape_probe.c
    probe=leanllvm_json_escape_list
    # `build49.sh:19-21`'s measured set plus `-DUS_EMIT4=1` (`:28`), the arm
    # the stage-2 consumer's escape step is built at.
    defs=(-DSTAGE_PROBE -DS1F_ENT_PROBE=1 -DS1F_DENS=1 -DS1F_TWOPHASE=1
          -DS1F_EXP2=11 -DS1F_DISPATCH=1 -DS1F_UTF8=7 -DS1F_KL_DOC=1 -DPSTAGE=32
          -DPMODE=2 -DS1F_XS=5 -DS2_XP=1 -DS2_DEC_GATE=2 -DS1F_XS_DYN=1
          -DUS_EMIT4=1)
    lift=(-func=leanllvm_json_escape_list -func=leanllvm_json_escape_expand
          -func=us_dec_x)
    lift_functions="leanllvm_json_escape_expand leanllvm_json_escape_list us_dec_x"
    by_name=1
    generated=0
    ;;
  pipeline)
    kernel=$repo/kernel/json/pipeline.c
    # The pipeline has no measured counterpart: the three texts the arm relates
    # are the source's emission, its object, and the pinned fixture, and the
    # module is not lifted because the comparison is over the whole body.
    oracle=""
    probe_src=""
    probe=leanllvm_json_pipeline
    defs=()
    lift=(-func=leanllvm_json_pipeline)
    lift_functions="leanllvm_json_pipeline"
    by_name=0
    generated=0
    pipeline=1
    ;;
  *)
    printf 'SETUP: unit %s has no IR identity arm; implemented units: s1 entry utf8 escape pipeline\n' "$unit" >&2
    exit 3
    ;;
esac

inputs=("$kernel" "$readme")
[ -n "$oracle" ] && inputs+=("$oracle")
[ -n "$probe_src" ] && inputs+=("$probe_src")
measured=$repo/kernel/json/measured
[ "$generated" -eq 1 ] && inputs+=("$measured/s1fuse.h" "$measured/u8kl.h")
[ "$unit" = escape ] && inputs+=("$measured/s1fuse.h" "$measured/xlist.h" \
                                 "$measured/usdec.h" "$measured/uj.c")
[ "$pipeline" -eq 1 ] && inputs+=("$repo/probes/install/ir/json-pipeline.candidate.ll")

for path in "${inputs[@]}"; do
  [ -e "$path" ] || { printf 'SETUP: absent: %s\n' "$path" >&2; exit 3; }
done
for tool in "$cc" llvm-extract llvm-diff; do
  command -v "$tool" >/dev/null 2>&1 || {
    printf 'SETUP: no %s on PATH; Arm B needs the flake'"'"'s LLVM tools\n' "$tool" >&2
    exit 3
  }
done

require_in_tree() {
  case "$1" in
    "$repo"/*) return 0 ;;
    *) printf 'REFUSED: %s is outside %s and --tree-only was given\n' "$1" "$repo" >&2; exit 3 ;;
  esac
}
[ "$tree_only" -eq 1 ] && for path in "${inputs[@]}"; do require_in_tree "$path"; done

mkdir -p "$repo/.lake" || { printf 'SETUP: cannot create %s/.lake\n' "$repo" >&2; exit 3; }
work=$(mktemp -d "$repo/.lake/tmp-$unit-ir.XXXXXX" 2>/dev/null) || {
  printf 'SETUP: cannot create a work directory under %s/.lake\n' "$repo" >&2
  exit 3
}
trap 'rm -rf "$work"' EXIT

# compile_probe <name> <source> <extra include dir> [extra args...]
# Leaves $work/<name>.ll holding the module with the unit's symbols lifted out.
compile_probe() {
  local name=$1 src=$2 inc=$3
  shift 3
  local ll=$work/$name.ll lifted=$work/$name.probe.ll
  if ! "$cc" "${cflags[@]}" "${defs[@]}" "$@" -I "$inc" -S -emit-llvm \
      -o "$ll" "$src"; then
    printf 'SETUP: %s did not compile\n' "$src" >&2
    return 3
  fi
  if ! llvm-extract "${lift[@]}" -S "$ll" -o "$lifted"; then
    printf 'SETUP: llvm-extract could not lift %s out of %s\n' "${lift[*]}" "$ll" >&2
    return 3
  fi
  # No debug info is emitted (the flags carry no -g), so there is nothing to
  # strip; this LLVM 21.1.8 has no `strip-debug` pass to strip it with either.
  # The absence is asserted rather than assumed, so a later `-g` fails loudly
  # instead of making the comparison a comparison of debug metadata.
  if grep -qE '!llvm\.dbg|"Debug Info Version"' "$lifted"; then
    printf 'SETUP: %s carries debug info and this LLVM has no strip-debug pass\n' "$lifted" >&2
    printf 'SETUP: compile without -g, or add the strip step the toolchain provides\n' >&2
    return 3
  fi
  # The module's own file name (`ModuleID`, `source_filename`) is the input
  # path, not code; removing it from both sides leaves the comparison about the
  # emitted code and makes the two digests comparable.
  sed -i -e '/^; ModuleID = /d' -e '/^source_filename = /d' "$lifted"
  printf '%s' "$lifted"
}

# compare <expected:identical|different|report> <a.ll> <b.ll> <label>
# `report` prints which way `llvm-diff` went and asserts nothing: it is how a
# control shows what the instruction comparison can and cannot see.
compare() {
  local want=$1 a=$2 b=$3
  local label=$4
  local out="$work/diff.$label"
  local status
  llvm-diff "$a" "$b" > "$out" 2>&1
  status=$?
  if [ "$want" = report ]; then
    if [ "$status" -eq 0 ] && [ ! -s "$out" ]; then
      printf '   %s: llvm-diff reports no difference\n' "$label"
    else
      printf '   %s: llvm-diff reports a difference\n' "$label"
      awk 'NR <= 6 { printf "      %s\n", $0 }' "$out"
    fi
    return 0
  fi
  if [ "$want" = identical ]; then
    if [ "$status" -eq 0 ] && [ ! -s "$out" ]; then
      printf 'ok: %s: llvm-diff reports no difference\n' "$label"
      return 0
    fi
    printf 'FAIL: %s: llvm-diff reports a difference\n' "$label" >&2
    awk 'NR <= 40' "$out" >&2
    return 1
  fi
  if [ "$status" -ne 0 ] || [ -s "$out" ]; then
    printf 'ok: %s: reported as a difference\n' "$label"
    awk 'NR <= 6 { printf "      %s\n", $0 }' "$out"
    return 0
  fi
  printf 'FAIL: %s: the comparison did not see the mutation\n' "$label" >&2
  return 1
}

# --- the lifted module's shape, for the by-name unit ----------------------

# defined_functions <file> -- the sorted names of the functions it defines.
defined_functions() {
  awk '/^define / {
         name = $0
         sub(/.*@/, "", name); sub(/\(.*/, "", name)
         print name
       }' "$1" | LC_ALL=C sort
}

# global_definition <file> <name> -- the one line that defines the global.
global_definition() {
  awk -v name="$2" '
    $1 == "@" name && $2 == "=" {
      line = $0
      sub(/^[^ ]+ [^ ]+ /, "", line)
      if (line !~ /^external /) print $0
      found = 1
      exit
    }
    END { if (!found) printf "" }
  ' "$1"
}

assert_lifted_shape() { # <file> <side>
  local file=$1 side=$2 got
  got=$(defined_functions "$file")
  if [ "$got" != "$(printf '%s\n' $lift_functions | LC_ALL=C sort)" ]; then
    printf 'SETUP: the %s module defines {%s}, not {%s}\n' \
      "$side" "$(echo $got)" "$(echo $lift_functions)" >&2
    return 3
  fi
  printf 'ok: the %s module defines exactly %s\n' "$side" "$(echo $got | tr ' ' ',')"
}

# The table's definition, carried on both sides rather than excused from the
# comparison: `llvm-diff` compares code and not global initialisers, so this
# line is compared here.
compare_global() { # <expected:identical|different> <a.ll> <b.ll> <label>
  local want=$1 a=$2 b=$3 label=$4
  local la lb
  la=$(global_definition "$a" xl_pos8)
  lb=$(global_definition "$b" xl_pos8)
  if [ -z "$la" ] || [ -z "$lb" ]; then
    printf 'SETUP: %s: a side does not define @xl_pos8\n' "$label" >&2
    return 3
  fi
  if [ "$want" = identical ]; then
    if [ "$la" = "$lb" ]; then
      printf 'ok: %s: @xl_pos8'"'"'s definition is identical\n     %s\n' "$label" "$la"
      return 0
    fi
    printf 'FAIL: %s: @xl_pos8'"'"'s definition differs\n     measured  %s\n     extracted %s\n' \
      "$label" "$la" "$lb" >&2
    return 1
  fi
  if [ "$la" != "$lb" ]; then
    printf 'ok: %s: @xl_pos8'"'"'s definition moved\n     measured  %s\n     mutated   %s\n' \
      "$label" "$la" "$lb"
    return 0
  fi
  printf 'FAIL: %s: the global comparison did not see the mutation\n' "$label" >&2
  return 1
}

# --- the metadata comparison ----------------------------------------------

# The s1 unit's one named cause: the TBAA struct-path node of the carry type.
# The enumerated deletion of `prevS`, `bs_prevb` and `bs_prevs` leaves the
# kernel's carry with three fields where the measured `S1F` has six, and the
# node lists one `i64` offset per field.  Anything else is a finding.
metadata_cause() { # <measured.ll> <kernel.ll>
  local a=$1 b=$2
  local am=$work/meta.measured bm=$work/meta.kernel
  local an= bn= deleted= k=
  awk '/^!/' "$a" > "$am"
  awk '/^!/' "$b" > "$bm"
  if cmp -s "$am" "$bm"; then
    printf 'metadata: identical\n'
    return 0
  fi
  if ! grep -qE '^![0-9]+ = !\{!"",' "$am" || ! grep -qE '^![0-9]+ = !\{!"",' "$bm"; then
    printf 'FINDING: the metadata sections differ and neither side names an unnamed-struct node\n' >&2
    diff -u "$am" "$bm" | awk 'NR <= 20 { printf "      %s\n", $0 }' >&2
    return 1
  fi
  an=$(grep -m1 -E '^![0-9]+ = !\{!"",' "$am" | grep -o 'i64' | wc -l | tr -d ' ')
  bn=$(grep -m1 -E '^![0-9]+ = !\{!"",' "$bm" | grep -o 'i64' | wc -l | tr -d ' ')
  awk '{ if ($0 ~ /^![0-9]+ = !\{!"",/) sub(/\{!"",.*\}$/, "{!\"\", <fields>}"); print }' \
    "$am" > "$work/meta.measured.norm"
  awk '{ if ($0 ~ /^![0-9]+ = !\{!"",/) sub(/\{!"",.*\}$/, "{!\"\", <fields>}"); print }' \
    "$bm" > "$work/meta.kernel.norm"
  if ! cmp -s "$work/meta.measured.norm" "$work/meta.kernel.norm"; then
    printf 'FINDING: the metadata sections differ beyond the carry type'"'"'s field count\n' >&2
    diff -u "$work/meta.measured.norm" "$work/meta.kernel.norm" \
      | awk 'NR <= 20 { printf "      %s\n", $0 }' >&2
    return 1
  fi
  deleted=$(sed -n '/<!-- identity-list:begin -->/,/<!-- identity-list:end -->/p' "$readme" \
    | sed -n 's/^carry-fields-deleted:[[:space:]]*//p')
  if [ -z "$deleted" ]; then
    printf 'FINDING: metadata differs (struct-path %s -> %s) and no deleted carry field is recorded\n' \
      "$an" "$bn" >&2
    return 1
  fi
  k=$(printf '%s\n' $deleted | wc -l | tr -d ' ')
  if [ "$((an - bn))" -ne "$k" ]; then
    printf 'FINDING: metadata differs (struct-path %s -> %s) but %s carry field(s) are recorded as deleted\n' \
      "$an" "$bn" "$k" >&2
    return 1
  fi
  printf 'metadata: struct-path field count %s -> %s, from the enumerated deletion of %s\n' \
    "$an" "$bn" "$deleted"
  printf '          the identity is the instruction text; this difference has the cause named above\n'
  return 0
}

# canon_metadata <file> -- one line per metadata node, sorted: the node's text
# with every reference replaced by the referenced node's canonical text, so the
# numbering a module happens to assign cancels out.
canon_metadata() { # <file>
  awk '
    /^![0-9]+ = / {
      id = $1
      text = $0
      sub(/^[^ ]+ = /, "", text)
      txt[id] = text
      ids[++n] = id
    }
    END { for (i = 1; i <= n; i++) print label(ids[i]) }
    function label(id,   t, out) {
      if (id in memo) return memo[id]
      if (id in busy) return "SELF"
      if (!(id in txt)) return "UNRESOLVED"
      busy[id] = 1
      t = txt[id]
      out = ""
      while (match(t, /![0-9]+/)) {
        out = out substr(t, 1, RSTART - 1) "!" label(substr(t, RSTART + 1, RLENGTH - 1))
        t = substr(t, RSTART + RLENGTH)
      }
      out = out t
      delete busy[id]
      memo[id] = out
      return out
    }
  ' "$1" | LC_ALL=C sort
}

# metadata_graph <a.ll> <b.ll> -- the entry unit's no-exclusion comparison.
metadata_graph() { # <measured.ll> <extracted.ll>
  local a=$1 b=$2 count
  canon_metadata "$a" > "$work/meta.graph.measured"
  canon_metadata "$b" > "$work/meta.graph.extracted"
  count=$(wc -l < "$work/meta.graph.measured" | tr -d ' ')
  if cmp -s "$work/meta.graph.measured" "$work/meta.graph.extracted"; then
    printf 'ok: metadata: %s nodes, equal as a graph (node numbering is per-module)\n' "$count"
    return 0
  fi
  printf 'FINDING: the metadata graphs differ\n' >&2
  diff -u "$work/meta.graph.measured" "$work/meta.graph.extracted" \
    | awk 'NR <= 20 { printf "      %s\n", $0 }' >&2
  return 1
}

# compare_code_text <expected:identical|different> <a.ll> <b.ll> <label>
# The module's text before its metadata section, digested.  This is the
# instrument that sees what `llvm-diff` does not: the instruction flags.  A
# `nuw` removed from a `shl` is a difference in this digest and no difference to
# `llvm-diff` (measured on LLVM 21.1.8), so both are printed where a control
# exercises one.
compare_code_text() { # <expected> <a.ll> <b.ll> <label>
  local want=$1 a=$2 b=$3 label=$4 da db
  da=$(awk '/^!/{exit} {print}' "$a" | sha256sum | cut -d' ' -f1)
  db=$(awk '/^!/{exit} {print}' "$b" | sha256sum | cut -d' ' -f1)
  if [ "$want" = identical ]; then
    printf '   code text digest\n     a %s\n     b %s\n' "$da" "$db"
    if [ "$da" = "$db" ]; then
      printf 'ok: %s: the code text is byte-identical, instruction flags included\n' "$label"
      return 0
    fi
    printf 'FAIL: %s: the code text differs outside the metadata section\n' "$label" >&2
    diff -u <(awk '/^!/{exit} {print}' "$a") <(awk '/^!/{exit} {print}' "$b") \
      | awk 'NR <= 40' >&2
    return 1
  fi
  if [ "$da" != "$db" ]; then
    printf 'ok: %s: the code text is reported as a difference\n' "$label"
    return 0
  fi
  printf 'FAIL: %s: the code-text comparison did not see the mutation\n' "$label" >&2
  return 1
}

# --- the identity ---------------------------------------------------------

# build_stage_side [extra include dir] -- the UTF-8 unit's measured side.  The
# translation unit comes from the token arm's own helper, so the stage text has
# one definition and there is no second copy to drift; the optional directory is
# put first on the include path so a control can compile against a mutated copy
# of the vendored pair, which is how its table control is applied.
build_stage_side() { # <name> [extra include dir]
  local name=$1 tu=$work/side-a.$1.c
  if ! bash "$oracle" --unit utf8 --stage-tu > "$tu"; then
    printf 'SETUP: the measured side could not be generated\n' >&2
    return 3
  fi
  if [ ! -s "$tu" ]; then
    printf 'SETUP: the generated measured side is empty\n' >&2
    return 3
  fi
  if [ -n "${2:-}" ]; then
    compile_probe "stage_a_$name" "$tu" "$measured" -I "$2"
  else
    compile_probe "stage_a_$name" "$tu" "$measured"
  fi
}

# --- the pipeline's three texts --------------------------------------------

# ir_census <module> -- the project call targets the module carries, as
# `<name> <count>` lines.
ir_census() { # <file.ll>
  awk '
    /call .*@leanllvm_json_/ {
      line = $0
      while (match(line, /@leanllvm_json_[a-z0-9_]+/)) {
        n = substr(line, RSTART + 1, RLENGTH - 1)
        c[n]++
        line = substr(line, RSTART + RLENGTH)
      }
    }
    END { for (n in c) print n, c[n] }
  ' "$1" | LC_ALL=C sort
}

# object_census <object> -- the project call targets the object carries.  A
# call across the object's sections is a PLT32 relocation, and the pipeline
# calls no library function, so this is its census and not a filter.
object_census() { # <object>
  readelf -rW "$1" | awk '
    $3 == "R_X86_64_PLT32" && $5 ~ /^leanllvm_json_/ {
      n = $5
      sub(/-.*$/, "", n)
      c[n]++
    }
    END { for (n in c) print n, c[n] }
  ' | LC_ALL=C sort
}

arm_identity_pipeline() {
  local emission pinned object
  printf '\n== Arm B (%s): the emission, the object, and the pinned fixture\n' "$unit"
  for tool in readelf nm; do
    command -v "$tool" >/dev/null 2>&1 || {
      printf 'SETUP: no %s on PATH\n' "$tool" >&2
      return 3
    }
  done
  if ! "$cc" "${cflags[@]}" -I "$repo/kernel/json" -S -emit-llvm \
      -o "$work/pipeline.ll" "$kernel"; then
    printf 'SETUP: the pipeline did not emit IR\n' >&2
    return 3
  fi
  if ! "$cc" "${cflags[@]}" -I "$repo/kernel/json" -c \
      -o "$work/pipeline.o" "$kernel"; then
    printf 'SETUP: the pipeline did not compile\n' >&2
    return 3
  fi
  emission=$(ir_census "$work/pipeline.ll")
  pinned=$(ir_census "$repo/probes/install/ir/json-pipeline.candidate.ll")
  object=$(object_census "$work/pipeline.o")
  if [ -z "$emission" ] || [ -z "$pinned" ] || [ -z "$object" ]; then
    printf 'SETUP: one of the three call censuses is empty\n' >&2
    return 3
  fi
  if [ "$emission" != "$pinned" ]; then
    printf 'FAIL: the pinned fixture is not the emission of %s\n' "$kernel" >&2
    diff -u <(printf '%s\n' "$pinned") <(printf '%s\n' "$emission") \
      | awk 'NR <= 20' >&2
    return 1
  fi
  printf 'ok: the pinned fixture'"'"'s call census is the emission'"'"'s\n'
  if [ "$object" != "$emission" ]; then
    printf 'FAIL: the object built from the same source has a different call census\n' >&2
    diff -u <(printf '%s\n' "$emission") <(printf '%s\n' "$object") \
      | awk 'NR <= 20' >&2
    return 1
  fi
  printf 'ok: the object built from that same source has the same call census\n'
  printf '   the census (the sites the emission has after loop unswitching):\n'
  printf '%s\n' "$emission" | awk '{ printf "     %-32s %s\n", $1, $2 }'
  if ! nm --defined-only "$work/pipeline.o" \
      | awk '$3 == "leanllvm_json_pipeline" { found = 1 } END { exit !found }'; then
    printf 'SETUP: the object does not define leanllvm_json_pipeline\n' >&2
    return 3
  fi
  printf 'ok: the object defines leanllvm_json_pipeline\n'
  return 0
}

arm_controls_pipeline() {
  local mut got pinned rc=0
  if [ ! -s "$work/pipeline.ll" ]; then
    if ! "$cc" "${cflags[@]}" -I "$repo/kernel/json" -S -emit-llvm \
        -o "$work/pipeline.ll" "$kernel"; then
      printf 'SETUP: the pipeline did not emit IR\n' >&2
      return 3
    fi
  fi
  pinned=$(ir_census "$work/pipeline.ll")

  printf '\n== Control: one call target changed in a copy of the source\n'
  mut=$work/pipeline.control.c
  awk '
    { if (!done && index($0, "leanllvm_json_entry_pos8(entw") > 0) {
        sub(/leanllvm_json_entry_pos8\(entw/, "leanllvm_json_entry_b8(entw")
        done = 1
      }
      print }
    END { if (!done) exit 1 }
  ' "$kernel" > "$mut" || {
    printf 'SETUP: the source control did not apply\n' >&2
    return 3
  }
  if ! "$cc" "${cflags[@]}" -I "$repo/kernel/json" -S -emit-llvm \
      -o "$work/pipeline.control.ll" "$mut"; then
    printf 'SETUP: the source control did not emit IR\n' >&2
    return 3
  fi
  got=$(ir_census "$work/pipeline.control.ll")
  if [ "$got" = "$pinned" ]; then
    printf 'FAIL: the census did not see the changed call target\n' >&2
    rc=1
  else
    printf 'ok: the changed call target is reported as a different census\n'
    printf '   %s\n' "$(echo $got)"
  fi

  printf '\n== Control: one call removed from a copy of the pinned fixture\n'
  mut=$work/pipeline.fixture.ll
  awk '
    { if (!done && index($0, "call") > 0 &&
          index($0, "@leanllvm_json_utf8(") > 0) { done = 1; next }
      print }
    END { if (!done) exit 1 }
  ' "$repo/probes/install/ir/json-pipeline.candidate.ll" > "$mut" || {
    printf 'SETUP: the fixture control did not apply\n' >&2
    return 3
  }
  got=$(ir_census "$mut")
  if [ "$got" = "$pinned" ]; then
    printf 'FAIL: the fixture comparison did not see the removed call\n' >&2
    rc=1
  else
    printf 'ok: the removed call is reported as a different census\n'
    printf '   %s\n' "$(echo $got)"
  fi
  return "$rc"
}

arm_identity() {
  local a b ca cb
  if [ "$pipeline" -eq 1 ]; then
    arm_identity_pipeline
    return $?
  fi
  printf '\n== Arm B (%s): emitted-code identity\n' "$unit"
  if [ "$generated" -eq 1 ]; then
    a=$(build_stage_side measured) || return 3
    b=$(compile_probe kernel "$kernel" "$repo/kernel/json") || return 3
    assert_lifted_shape "$a" measured || return $?
    assert_lifted_shape "$b" extracted || return $?
    compare identical "$a" "$b" identity || return 1
    compare_code_text identical "$a" "$b" identity || return 1
    metadata_graph "$a" "$b" || return 1
    return 0
  fi
  a=$(compile_probe oracle "$oracle" "$here") || return 3
  b=$(compile_probe kernel "$probe_src" "$repo/kernel/json") || return 3
  if [ "$by_name" -eq 1 ]; then
    assert_lifted_shape "$a" measured || return $?
    assert_lifted_shape "$b" extracted || return $?
  fi
  if [ "$by_name" -eq 0 ]; then
    ca=$(awk '/^!/{exit} {print}' "$a" | sha256sum | cut -d' ' -f1)
    cb=$(awk '/^!/{exit} {print}' "$b" | sha256sum | cut -d' ' -f1)
    printf '   code text digest (the module before its metadata section)\n'
    printf '     measured  %s\n' "$ca"
    printf '     extracted %s\n' "$cb"
  fi
  compare identical "$a" "$b" identity || return 1
  if [ "$by_name" -eq 0 ]; then
    if [ "$ca" = "$cb" ]; then
      printf 'ok: the code text is byte-identical\n'
    else
      printf 'FAIL: the code text differs outside the metadata section\n' >&2
      diff -u <(awk '/^!/{exit} {print}' "$a") <(awk '/^!/{exit} {print}' "$b") \
        | awk 'NR <= 40' >&2
      return 1
    fi
    metadata_cause "$a" "$b"
  elif [ "$unit" = escape ]; then
    # No global definition is part of this unit's interface: the decoder's
    # tables are constants inside the lifted functions' text, and the list has
    # no table at this arm.  The instruction comparison is the claim; the
    # metadata comparison is the canonical-graph form, because each side is
    # serialised from a different source module.
    metadata_graph "$a" "$b"
  else
    compare_global identical "$a" "$b" identity || return 1
    metadata_graph "$a" "$b"
  fi
}

# --- the controls ---------------------------------------------------------

# mutate_probe <name> <mutated kernel file>
# Builds a probe TU over the mutated copy in $work and echoes its module.
mutate_probe() {
  local name=$1 src=$2
  cat > "$work/$name.c" <<EOF
#include "$src"
void $probe(const uint8_t *p, void *st, uint64_t *out) {
    __m256i v0 = _mm256_loadu_si256((const __m256i *)(const void *)p);
    __m256i v1 = _mm256_loadu_si256((const __m256i *)(const void *)(p + 32));
    s1f_masks(v0, v1, (S1F *)st, &out[0], &out[1], &out[2], &out[3], &out[4],
              &out[5]);
}
EOF
  compile_probe "$name" "$work/$name.c" "$repo/kernel/json"
}

# mutate_entry_probe <name> <mutated kernel file> -- the entry unit's shape.
mutate_entry_probe() {
  local name=$1 src=$2
  cat > "$work/$name.c" <<EOF
#include "$src"
uint64_t $probe(uint64_t *ent, uint64_t blk0, uint64_t nblk,
                uint32_t *out, uint64_t k, int kern) {
    return kern ? s1f_k_b8(ent, blk0, nblk, out, k)
                : s1f_k_pos8(ent, blk0, nblk, out, k);
}
EOF
  compile_probe "$name" "$work/$name.c" "$repo/kernel/json"
}

# The UTF-8 unit's two controls.  The table is folded into constants by the
# optimiser, so a changed byte reaches the module only through the measured
# side's own copy of the vendored pair: the control compiles that side against
# a throwaway directory holding `s1fuse.h` unchanged and `u8kl.h` with one byte
# moved, which is what the unit's six entities were copied from.  The second
# control removes one `nuw` from the measured side's lifted IR, because that
# flag is part of what this arm compares and a comparison blind to it would let
# an arithmetic change through.
arm_controls_utf8() {
  local base mut header_dir module clean rc=0
  base=$(compile_probe kernel "$kernel" "$repo/kernel/json") || return 3
  clean=$(build_stage_side clean) || return 3

  printf '\n== Control: one byte of kl_t1 changed, in the measured side'"'"'s copy\n'
  header_dir=$work/header
  mkdir -p "$header_dir" || return 3
  cp "$measured/s1fuse.h" "$measured/u8kl.h" "$header_dir/" || return 3
  awk '
    { if (!done && index($0, "0xe7,") > 0) { sub(/0xe7,/, "0xe5,"); done = 1 } print }
    END { if (!done) exit 1 }
  ' "$header_dir/u8kl.h" > "$header_dir/u8kl.h.mut" || {
    printf 'SETUP: the table control did not apply to u8kl.h\n' >&2
    return 3
  }
  if cmp -s "$header_dir/u8kl.h" "$header_dir/u8kl.h.mut"; then
    printf 'SETUP: the table control could not rewrite a byte\n' >&2
    return 3
  fi
  mv "$header_dir/u8kl.h.mut" "$header_dir/u8kl.h" || return 3
  module=$(build_stage_side table "$header_dir") || return 3
  compare different "$module" "$clean" table || rc=1

  printf '\n== Control: one nuw removed from the measured side'"'"'s IR\n'
  mut=$work/side-a.nowu.ll
  awk '
    { if (!done && index($0, " nuw ") > 0) { sub(/ nuw /, " "); done = 1 } print }
    END { if (!done) exit 1 }
  ' "$clean" > "$mut" || {
    printf 'SETUP: the nuw control did not apply; the measured side carries no nuw\n' >&2
    return 3
  }
  printf '   one nuw removed from %s\n' "$(basename "$mut")"
  # Both verdicts, because they differ and the difference is the finding:
  # `llvm-diff` does not compare instruction flags, and the code-text digest
  # does.  The arm's flag claim rests on the second.
  compare report "$mut" "$clean" nuw-instruction
  compare_code_text different "$mut" "$clean" nuw-code-text || rc=1

  # The controls are about the measured side; `base` is still built above so an
  # absent unit fails this arm the same way the identity half does.
  [ -n "$base" ] || return 3
  return "$rc"
}

# mutate_escape_probe <name> <mutated kernel file> -- the escape unit's shape:
# the mutated copy is the whole unit, included as its own translation unit.
mutate_escape_probe() {
  local name=$1 src=$2
  printf '#include "%s"\n' "$src" > "$work/$name.c"
  compile_probe "$name" "$work/$name.c" "$repo/kernel/json"
}

# The escape unit's two controls, one in each half of the unit: a numeral in
# the list's batch and a bound in the decoder.  Both change instruction text,
# which is what `llvm-diff` compares; if either half were compared against
# itself the control would report no difference and fail the arm.
arm_controls_escape() {
  local base mut module rc=0
  base=$(compile_probe kernel "$probe_src" "$repo/kernel/json") || return 3

  printf '\n== Control: one numeral in xl_batch changed\n'
  mut=$work/escape.batch.c
  awk '
    { if (!done && index($0, "0x8000000000000000ULL") > 0) {
        sub(/0x8000000000000000ULL/, "0x8000000000000001ULL"); done = 1 }
      print }
    END { if (!done) exit 1 }
  ' "$kernel" > "$mut" || {
    printf 'SETUP: the batch control did not apply; the numeral is absent\n' >&2
    return 3
  }
  module=$(mutate_escape_probe kernel_batch "$mut") || return 3
  compare different "$base" "$module" batch || rc=1

  printf '\n== Control: the decoder bound pos0 + n changed\n'
  mut=$work/escape.endp.c
  awk '
    { if (!done && index($0, "uint64_t endp = pos0 + n;") > 0) {
        sub(/pos0 \+ n;/, "pos0 + n + 1;"); done = 1 }
      print }
    END { if (!done) exit 1 }
  ' "$kernel" > "$mut" || {
    printf 'SETUP: the decoder control did not apply; the bound is absent\n' >&2
    return 3
  }
  module=$(mutate_escape_probe kernel_endp "$mut") || return 3
  compare different "$base" "$module" endp || rc=1

  return "$rc"
}

arm_controls() {
  if [ "$pipeline" -eq 1 ]; then
    arm_controls_pipeline
    return $?
  fi
  if [ "$generated" -eq 1 ]; then
    arm_controls_utf8
    return $?
  fi
  if [ "$unit" = escape ]; then
    arm_controls_escape
    return $?
  fi
  if [ "$by_name" -eq 1 ]; then
    arm_controls_entry
    return $?
  fi

  local base mut module rc=0
  base=$(compile_probe kernel "$probe_src" "$repo/kernel/json") || return 3

  # --mutate-table: bit 0 of the first byte of `s1f_lo_tab`.
  mut=$work/s1_block.table.c
  awk '
    { if (!done && index($0, "s1f_lo_tab[32]") > 0) in_tab = 1
      if (in_tab && !done && index($0, "0x40,") > 0) { sub(/0x40,/, "0x41,"); done = 1 }
      print }
  ' "$kernel" > "$mut"
  if cmp -s "$kernel" "$mut"; then
    printf 'SETUP: the table control did not apply to %s\n' "$kernel" >&2
    return 3
  fi
  printf '\n== Control: one byte of s1f_lo_tab changed\n'
  module=$(mutate_probe kernel_table "$mut") || return 3
  compare different "$base" "$module" table || rc=1

  # --mutate-op: the left operand of `s1f_escaped`'s `alt = even_slots ^ …`.
  mut=$work/s1_block.op.c
  awk '
    { if (!done && index($0, "0x5555555555555555ULL") > 0) {
        sub(/0x5555555555555555ULL/, "0x5555555555555554ULL"); done = 1 }
      print }
  ' "$kernel" > "$mut"
  if cmp -s "$kernel" "$mut"; then
    printf 'SETUP: the operand control did not apply to %s\n' "$kernel" >&2
    return 3
  fi
  printf '\n== Control: one operand in s1f_escaped changed\n'
  module=$(mutate_probe kernel_op "$mut") || return 3
  compare different "$base" "$module" operand || rc=1

  return "$rc"
}

# The entry unit's two controls.  The table's rows are written at run time, so
# the only place a table byte reaches the module is the global's initialiser:
# the table control changes it there, and the global comparison is the
# instrument that reports it.  The slot control changes instruction text, which
# is what `llvm-diff` compares.
arm_controls_entry() {
  local base mut module rc=0 st=0
  base=$(compile_probe kernel "$probe_src" "$repo/kernel/json") || return 3

  # --mutate-table: row 0x2C's first entry, 2 -> 1, carried as the global's
  # initialiser (row 0x2C's set lanes are 2, 3 and 5, so the measured row opens
  # with 2).
  mut=$work/entry.table.c
  awk '
    { if (!done && index($0, "static uint32_t xl_pos8[256][8]") > 0) {
        sub(/;[ \t]*$/, " = {[0x2C] = {1}};")
        done = 1 }
      print }
  ' "$kernel" > "$mut"
  if cmp -s "$kernel" "$mut"; then
    printf 'SETUP: the table control did not apply to %s\n' "$kernel" >&2
    return 3
  fi
  printf '\n== Control: table row 0x2C changed, as the global'"'"'s initialiser\n'
  module=$(mutate_entry_probe kernel_table "$mut") || return 3
  compare report "$base" "$module" table-instruction
  compare_global different "$base" "$module" table-global
  st=$?
  [ "$st" -ne 0 ] && rc=$st
  if [ "$rc" -eq 0 ]; then
    printf '   the instruction comparison does not see an initialiser (it compares code);\n'
    printf '   the global comparison is what reports this control, which is why it is here\n'
  fi

  # --mutate-slot: the fifth slot's index in `s1f_ke_b8`'s chain.
  mut=$work/entry.slot.c
  awk '
    { if (!done && index($0, "o[5] = base +") > 0) {
        sub(/o\[5\] = base \+/, "o[6] = base +"); done = 1 }
      print }
  ' "$kernel" > "$mut"
  if cmp -s "$kernel" "$mut"; then
    printf 'SETUP: the slot control did not apply to %s\n' "$kernel" >&2
    return 3
  fi
  printf '\n== Control: one slot index in s1f_ke_b8 changed\n'
  module=$(mutate_entry_probe kernel_slot "$mut") || return 3
  compare different "$base" "$module" slot-instruction
  st=$?
  [ "$st" -ne 0 ] && rc=$st
  compare_global identical "$base" "$module" slot-global
  st=$?
  [ "$st" -ne 0 ] && rc=$st

  return "$rc"
}

